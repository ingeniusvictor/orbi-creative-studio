const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'electron', 'generated');
const OUT_FILE = path.join(OUT_DIR, 'buildIdentity.js');
const SHA_RE = /^[0-9a-f]{40}$/i;

function normalizeSha(value, label) {
    if (typeof value !== 'string' || !SHA_RE.test(value.trim())) {
        throw new Error(`${label} must be a 40-character Git commit SHA`);
    }
    return value.trim().toLowerCase();
}

function readGitHead() {
    try {
        return normalizeSha(
            execFileSync('git', ['rev-parse', 'HEAD'], {
                cwd: ROOT,
                encoding: 'utf8',
                stdio: ['ignore', 'pipe', 'ignore'],
            }),
            'git HEAD',
        );
    } catch {
        return undefined;
    }
}

function readEnvironmentSha() {
    const candidates = [
        ['ORBI_BUILD_SHA', process.env.ORBI_BUILD_SHA],
        ['GITHUB_SHA', process.env.GITHUB_SHA],
        ['VERCEL_GIT_COMMIT_SHA', process.env.VERCEL_GIT_COMMIT_SHA],
        ['CI_COMMIT_SHA', process.env.CI_COMMIT_SHA],
    ];

    for (const [name, value] of candidates) {
        if (value == null || value === '') continue;
        return Object.freeze({
            name,
            sha: normalizeSha(value, name),
        });
    }

    return undefined;
}

function resolveBuildSha() {
    const gitHead = readGitHead();
    const environment = readEnvironmentSha();

    if (process.env.ORBI_BUILD_SHA && gitHead) {
        const explicit = normalizeSha(process.env.ORBI_BUILD_SHA, 'ORBI_BUILD_SHA');
        if (explicit !== gitHead) {
            throw new Error(
                `ORBI_BUILD_SHA does not match checked-out git HEAD (${explicit} !== ${gitHead})`,
            );
        }
    }

    if (gitHead) return gitHead;
    if (environment) return environment.sha;

    throw new Error(
        'Unable to resolve exact build identity. A Git checkout or a valid ORBI_BUILD_SHA/GITHUB_SHA/VERCEL_GIT_COMMIT_SHA/CI_COMMIT_SHA is required.',
    );
}

function readAppVersion() {
    const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
    if (typeof pkg.version !== 'string' || !pkg.version.trim()) {
        throw new Error('package.json version is missing');
    }
    return pkg.version.trim();
}

function serialize(identity) {
    return [
        "'use strict';",
        '',
        '// AUTO-GENERATED by scripts/write-build-identity.js. DO NOT EDIT.',
        `module.exports = Object.freeze(${JSON.stringify(identity, null, 4)});`,
        '',
    ].join('\n');
}

function writeAtomic(file, content) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const temp = `${file}.tmp-${process.pid}`;
    fs.writeFileSync(temp, content, { encoding: 'utf8', mode: 0o600 });
    fs.renameSync(temp, file);
}

const identity = Object.freeze({
    schemaVersion: 1,
    sourceCommit: resolveBuildSha(),
    appVersion: readAppVersion(),
});

writeAtomic(OUT_FILE, serialize(identity));
console.log(
    `ORBI_BUILD_IDENTITY sourceCommit=${identity.sourceCommit} appVersion=${identity.appVersion}`,
);
